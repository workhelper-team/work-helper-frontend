// ==========================================================
// 상담 메시지 관련 타입 정의
//
// 백엔드 ConsultationMessage에서 내려주는 데이터를
// 프론트엔드에서 어떤 형태로 사용할지 정의한다.
// ==========================================================


// ==========================================================
// 메시지 역할
//
// USER     : 사용자가 작성한 상담 메시지
// ASSISTANT: 상담 AI 또는 시스템이 보낸 메시지
// ==========================================================
export type MessageRole = 'USER' | 'ASSISTANT'


// ==========================================================
// 상담 메시지
//
// GET /api/cases/{caseId}/messages
// 응답으로 받는 메시지 하나의 형태
// ==========================================================
export interface ConsultationMessage {
  // 메시지 고유 ID
  messageId: number

  // 해당 사건의 ID
  caseId: number

  // 메시지를 작성한 주체
  role: MessageRole

  // 실제 상담 내용
  content: string

  // 구조화된 결과
  //
  // 현재는 백엔드에서 null일 수 있으므로
  // 유연하게 처리한다.
  structuredResult: unknown | null

  // 메시지가 생성된 시간
  createdAt: string
}


// ==========================================================
// 상담 메시지 등록 요청
//
// POST /api/cases/{caseId}/messages
// ==========================================================
export interface SendConsultationMessageRequest {
  // 사용자가 입력한 상담 내용
  content: string
}